import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { buildKB } from './kb.mjs';
import { refreshGitHub } from './github.mjs';
refreshGitHub();
// Run with Node.js: node scripts/build.mjs. Deploy the generated dist/ directory.
const root = path.resolve(import.meta.dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
// Pre-render selected projects using exactly the same content and renderer as the browser.
const nodes = new Map();
const context = vm.createContext({URL, document:{querySelector(selector){if(!nodes.has(selector))nodes.set(selector, {innerHTML:''});return nodes.get(selector);}}});
const main = read('js/main.js');
const marker = main.indexOf('/* BROWSER-ONLY');
if (marker < 0) throw new Error('BROWSER-ONLY marker missing from js/main.js');
vm.runInContext(read('js/github-data.js') + '\n' + read('js/data.js') + '\n' + main.slice(0, marker) + '\nrenderCases();renderOss();renderMore();renderBackground();renderGitHub();', context);
let html = read('index.html');
for (const id of ['cases', 'oss', 'github-block', 'more-list', 'background-list']) {
  const start = `<!-- ${id}:start -->`, end = `<!-- ${id}:end -->`;
  const content = `<div id="${id}">${nodes.get('#'+id).innerHTML}</div>`;
  if (html.includes(start)) html = html.slice(0, html.indexOf(start)) + start + content + end + html.slice(html.indexOf(end) + end.length);
  else html = html.replace(`<div id="${id}"></div>`, start + content + end);
}
fs.writeFileSync(path.join(root,'index.html'),html);
const kbCtx = vm.createContext({});
vm.runInContext(read('js/data.js') + '\n;this.out={CASES,HOME,FLAGSHIP,DATA_PROJECTS,MISC_PROJECTS,SOURCES,EDUCATION,EXPERIENCE,ACHIEVEMENTS,CONTACT};', kbCtx);
// The agent's knowledge: generated from the same data as the page.
fs.writeFileSync(path.join(root,'lib','kb.js'), '// Generated by scripts/build.mjs from js/data.js. Do not edit.\nexport const KB = ' + JSON.stringify(buildKB(kbCtx.out), null, 1) + ';\n');
const dist = path.join(root, 'dist');
if (path.dirname(dist) !== root || path.basename(dist) !== 'dist') throw new Error('Invalid build output path');
fs.rmSync(dist, {recursive:true, force:true});
fs.mkdirSync(dist, {recursive:true});
for (const file of ['index.html','resume.html','robots.txt','sitemap.xml','_headers']) fs.copyFileSync(path.join(root,file),path.join(root,'dist',file));
for (const dir of ['css','js','assets']) fs.cpSync(path.join(root,dir),path.join(root,'dist',dir),{recursive:true});
console.log('Pre-rendered selected projects and refreshed dist from source.');

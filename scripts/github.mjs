// Refreshes js/github-data.js from the GitHub API (needs the `gh` CLI, logged in).
// Run: node scripts/github.mjs   (build.mjs runs it too; if gh is unavailable the old file is kept).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'js', 'github-data.js');
const USER = 'eshitakundu';
const HIDE = new Set(['NeuraSeek', 'eshitakundu', 'portfolio']);            // never featured
const EXTERNAL = ['amd/gaia', 'CrossGL/crosstl', 'rohitg00/ai-engineering-from-scratch'];

const gh = (args) => JSON.parse(execFileSync('gh', args, { encoding: 'utf8', maxBuffer: 32 << 20 }));

export function refreshGitHub() {
  try {
    const q = `query{user(login:"${USER}"){repositories(ownerAffiliations:OWNER,privacy:PUBLIC,isFork:false,first:100,orderBy:{field:PUSHED_AT,direction:DESC}){totalCount nodes{name description stargazerCount homepageUrl primaryLanguage{name} pushedAt}}
      contributionsCollection{totalCommitContributions totalPullRequestContributions contributionCalendar{totalContributions weeks{contributionDays{date contributionCount}}}}}}`;
    const u = gh(['api', 'graphql', '-f', `query=${q}`]).data.user;
    const cal = u.contributionsCollection.contributionCalendar;
    const days = cal.weeks.flatMap((w) => w.contributionDays.map((d) => [d.date, d.contributionCount]));
    const external = EXTERNAL.map((repo) => {
      const prs = gh(['search', 'prs', '--author', USER, '--merged', '--repo', repo, '--json', 'number', '--limit', '100']);
      return { repo, merged: prs.length, href: `https://github.com/${repo}/pulls?q=is%3Apr+author%3A${USER}+is%3Amerged` };
    });
    const repos = u.repositories.nodes.filter((r) => !HIDE.has(r.name)).slice(0, 6)
      .map((r) => ({ name: r.name, description: r.description || '', language: r.primaryLanguage?.name || '', pushed: r.pushedAt.slice(0, 10), href: `https://github.com/${USER}/${r.name}` }));
    const data = {
      fetched: new Date().toISOString().slice(0, 10),
      publicRepos: u.repositories.totalCount,
      yearContributions: cal.totalContributions,
      yearCommits: u.contributionsCollection.totalCommitContributions,
      yearPRs: u.contributionsCollection.totalPullRequestContributions,
      activeDays: days.filter((d) => d[1] > 0).length,
      days, external, recent: repos
    };
    // Keep the old file (and its date) when only the fetch date would change,
    // so the daily Action commits only when the numbers really changed.
    if (fs.existsSync(out)) {
      try {
        const prev = JSON.parse(fs.readFileSync(out, 'utf8').split('const GITHUB = ')[1].trim().replace(/;$/, ''));
        const same = JSON.stringify({ ...prev, fetched: '' }) === JSON.stringify({ ...data, fetched: '' });
        if (same) return prev;
      } catch {}
    }
    fs.writeFileSync(out, '// Generated by scripts/github.mjs from the GitHub API. Do not edit.\nconst GITHUB = ' + JSON.stringify(data) + ';\n');
    return data;
  } catch (e) {
    if (!fs.existsSync(out)) throw e;
    console.warn('github: kept existing js/github-data.js (' + String(e.message).split('\n')[0] + ')');
  }
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const d = refreshGitHub();
  if (d) console.log(`github: ${d.yearContributions} contributions, ${d.publicRepos} repos, external`, d.external.map((x) => `${x.repo}=${x.merged}`).join(' '));
}
